#!/usr/bin/env node
/**
 * AUDIT: room-mystery verb coverage
 *
 * Walks apps/shared/roomMysteries/*.ts (skipping tests, templates, and
 * the species-exclusive helper) and emits a coverage table:
 *
 *   roomId | hotspot count | look | use | talk | total / N×3
 *
 * The audit is text-only — no AST traversal — because the modules
 * follow a strict `verb: { ... }` literal pattern under each hotspot
 * key. This keeps the script dependency-free (no @typescript/parser)
 * and ~40× faster than a tsc-based walk.
 *
 * Use:
 *   node scripts/_audit-room-verb-coverage.mjs
 *   node scripts/_audit-room-verb-coverage.mjs --md > docs/production/room-pointclick-audit.md
 */
import { readdirSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOM_DIR = resolve(process.cwd(), "apps/shared/roomMysteries");
const SKIP = new Set(["_template.ts", "_speciesExclusive.ts", "index.ts"]);

const VERBS = ["look", "use", "talk", "interrogate"];

/** Find the start of the responses object literal in a module file. */
function findResponsesBlock(src) {
  const m = src.match(/responses\s*:\s*\{/);
  if (!m) return null;
  const start = m.index + m[0].length;
  // Walk braces to find the matching close.
  let depth = 1;
  let i = start;
  while (i < src.length && depth > 0) {
    const ch = src[i];
    if (ch === "{") depth++;
    else if (ch === "}") depth--;
    i++;
  }
  return depth === 0 ? src.slice(start, i - 1) : null;
}

/** Inside a responses block, slice each top-level hotspot entry.
 *  A hotspot is an identifier or quoted string followed by `: {`.
 *  After consuming each hotspot's body, fast-forward the regex past
 *  its end so nested keys (look: {…}) are not re-matched. */
function splitHotspots(block) {
  const out = [];
  const re = /(?:"([^"\\]+)"|([A-Za-z_][\w-]*))\s*:\s*\{/g;
  let match;
  while ((match = re.exec(block)) !== null) {
    const id = match[1] ?? match[2];
    const start = match.index + match[0].length;
    let depth = 1;
    let i = start;
    while (i < block.length && depth > 0) {
      const ch = block[i];
      if (ch === "{") depth++;
      else if (ch === "}") depth--;
      i++;
    }
    if (depth === 0) {
      out.push({ id, body: block.slice(start, i - 1) });
      re.lastIndex = i;
    } else {
      break;
    }
  }
  return out;
}

/** Count which verbs appear as keys at the top level of a hotspot body.
 *  The cheap pattern works because RoomMysteryModule responses are
 *  shallow object literals — `look: { ... }` etc. */
function countVerbs(body) {
  const seen = new Set();
  for (const verb of VERBS) {
    if (new RegExp(`(^|[^A-Za-z0-9_])${verb}\\s*:\\s*\\{`).test(body)) {
      seen.add(verb);
    }
  }
  return seen;
}

const files = readdirSync(ROOM_DIR)
  .filter(f => f.endsWith(".ts") && !f.endsWith(".test.ts") && !SKIP.has(f))
  .sort();

const rows = [];
for (const file of files) {
  const src = readFileSync(resolve(ROOM_DIR, file), "utf8");
  const block = findResponsesBlock(src);
  if (!block) {
    rows.push({ file, roomId: "?", hotspots: 0, look: 0, use: 0, talk: 0, interrogate: 0, total: 0, denom: 0 });
    continue;
  }
  const hotspots = splitHotspots(block);
  let look = 0, use = 0, talk = 0, interrogate = 0;
  for (const { body } of hotspots) {
    const seen = countVerbs(body);
    if (seen.has("look")) look++;
    if (seen.has("use")) use++;
    if (seen.has("talk")) talk++;
    if (seen.has("interrogate")) interrogate++;
  }
  // Extract roomId from the module: roomId: "..."
  const ridMatch = src.match(/roomId\s*:\s*"([^"]+)"/);
  const roomId = ridMatch ? ridMatch[1] : file.replace(/\.ts$/, "");
  const total = look + use + talk;
  const denom = hotspots.length * 3;
  rows.push({ file, roomId, hotspots: hotspots.length, look, use, talk, interrogate, total, denom });
}

const md = process.argv.includes("--md");
const detail = process.argv.includes("--detail");

if (detail) {
  // Per-hotspot, per-verb breakdown — tells you exactly which
  // (hotspot, verb) cells are unauthored so an authoring batch
  // doesn't have to grep each module by hand.
  for (const file of files) {
    const src = readFileSync(resolve(ROOM_DIR, file), "utf8");
    const block = findResponsesBlock(src);
    const ridMatch = src.match(/roomId\s*:\s*"([^"]+)"/);
    const roomId = ridMatch ? ridMatch[1] : file.replace(/\.ts$/, "");
    if (!block) {
      console.log(`${roomId}: no responses block`);
      continue;
    }
    const hotspots = splitHotspots(block);
    const missing = [];
    for (const { id, body } of hotspots) {
      const seen = countVerbs(body);
      const gaps = ["look", "use", "talk"].filter(v => !seen.has(v));
      if (gaps.length > 0) missing.push(`  ${id}: missing ${gaps.join(", ")}`);
    }
    if (missing.length > 0) {
      console.log(roomId);
      for (const m of missing) console.log(m);
    }
  }
  process.exit(0);
}

if (md) {
  console.log("# Room point-and-click verb-coverage audit\n");
  console.log("Generated by `scripts/_audit-room-verb-coverage.mjs`. Coverage = (look + use + talk) / (hotspots × 3).\n");
  console.log("| Room | Hotspots | Look | Use | Talk | Interrogate | Coverage |");
  console.log("|---|---:|---:|---:|---:|---:|---:|");
  for (const r of rows) {
    const pct = r.denom === 0 ? "—" : `${Math.round((r.total / r.denom) * 100)}%`;
    console.log(`| \`${r.roomId}\` | ${r.hotspots} | ${r.look} | ${r.use} | ${r.talk} | ${r.interrogate} | ${pct} |`);
  }
  console.log("");
  const grandTotal = rows.reduce((acc, r) => acc + r.total, 0);
  const grandDenom = rows.reduce((acc, r) => acc + r.denom, 0);
  const grandPct = grandDenom === 0 ? 0 : Math.round((grandTotal / grandDenom) * 100);
  console.log(`**Overall coverage:** ${grandTotal} / ${grandDenom} (${grandPct}%)`);
} else {
  const w = (s, n) => String(s).padEnd(n);
  console.log(w("ROOM", 28), w("HS", 4), w("LOOK", 5), w("USE", 4), w("TALK", 5), w("INTRG", 6), "COVERAGE");
  console.log("─".repeat(72));
  for (const r of rows) {
    const pct = r.denom === 0 ? "—" : `${Math.round((r.total / r.denom) * 100)}%`;
    console.log(
      w(r.roomId, 28),
      w(r.hotspots, 4),
      w(r.look, 5),
      w(r.use, 4),
      w(r.talk, 5),
      w(r.interrogate, 6),
      `${r.total}/${r.denom} (${pct})`,
    );
  }
  const grandTotal = rows.reduce((acc, r) => acc + r.total, 0);
  const grandDenom = rows.reduce((acc, r) => acc + r.denom, 0);
  const grandPct = grandDenom === 0 ? 0 : Math.round((grandTotal / grandDenom) * 100);
  console.log("─".repeat(72));
  console.log(`OVERALL: ${grandTotal}/${grandDenom} (${grandPct}%)`);
}
