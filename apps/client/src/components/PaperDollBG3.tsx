/* ═══════════════════════════════════════════════════════
   PAPER DOLL BG3 RENDERER (plan §G.9)

   Layers the composited paper-doll pieces over a 1024x1536
   canvas. Each composited slot renders its canonical PNG
   (/art/suits/<setId>/<rarity>/<slot>.png) through
   <ResponsiveImage>, which auto-prefers the .webp sibling
   generated by apps/scripts/optimize-images.ts.

   When a piece's artId is either not a suit-set id (e.g.,
   the starter `mask:…` / `suit:…` sentinels) or its PNG
   404s on load, that layer falls back to the slot's
   placeholder rectangle so nothing disappears while the
   remaining 16/18 suit sets are still being rendered by
   the art team.

   Opt-in via the DRESSUP_V2 feature flag — OFF by default:
     localStorage.setItem("DRESSUP_V2", "on")
   (or VITE_DRESSUP_V2=on at build time).
   ═══════════════════════════════════════════════════════ */

import { useState } from "react";
import {
  compositePaperDoll,
  hasRequiredBaseLayers,
  type Loadout,
  type CompositedLayer,
} from "@/game/paperDoll/compositePaperDoll";
import { parseSuitPieceArtId, suitArtUrl } from "@/game/paperDoll/suitArt";
import { bodyArtUrl, type BodySpecies } from "@/game/paperDoll/bodyArt";
import ResponsiveImage from "@/components/ResponsiveImage";
import type { SuitEquipSlot } from "@shared/suitEquipSlots";

interface Props {
  loadout: Loadout;
  /** Element tint applied to every layer with tintMask: true. CSS color string. */
  elementTint?: string;
  /** Canvas-width override (base is 1024 to match the art spec). */
  width?: number;
  /** Species silhouette PNG to render at the bottom of the z-stack (under
   *  every gear layer, above the aura). Omit to skip the body layer — the
   *  Suit Gallery passes nothing because it previews catalog sets, not
   *  characters. */
  bodySpecies?: BodySpecies;
  /** Show coloured slot rectangles when a piece's PNG hasn't shipped yet.
   *  ON in the Suit Gallery (so art QA can see what's missing); OFF for
   *  player-facing surfaces — the chronicle card should never leak slot
   *  labels like "weapon-primary" into the visual. */
  showPlaceholders?: boolean;
}

/** Canvas dimensions baked in §G.8. */
const CANVAS_W = 1024;
const CANVAS_H = 1536;

/** Per-slot placeholder rectangles — shown when the PNG isn't
 *  shipped yet or fails to load. Coordinates in the §G.8 pivot grid. */
const SLOT_RECTS: Record<SuitEquipSlot, {
  x: number;
  y: number;
  w: number;
  h: number;
  fill: string;
}> = {
  aura: { x: 256, y: 300, w: 512, h: 1000, fill: "#b6a8f2" },
  back: { x: 340, y: 340, w: 344, h: 900, fill: "#2b2414" },
  legs: { x: 390, y: 900, w: 244, h: 280, fill: "#13344a" },
  feet: { x: 400, y: 1380, w: 224, h: 80, fill: "#050506" },
  "base-suit": { x: 380, y: 320, w: 264, h: 1100, fill: "#221b2d" },
  chest: { x: 380, y: 380, w: 264, h: 380, fill: "#7a1e13" },
  belt: { x: 380, y: 760, w: 264, h: 70, fill: "#5b4a2a" },
  "weapon-offhand": { x: 260, y: 820, w: 100, h: 200, fill: "#8b47c2" },
  arms: { x: 340, y: 620, w: 344, h: 260, fill: "#4fa86b" },
  gloves: { x: 310, y: 860, w: 60, h: 60, fill: "#d9a23b" },
  shoulders: { x: 360, y: 340, w: 304, h: 100, fill: "#3b6edb" },
  neck: { x: 460, y: 300, w: 104, h: 60, fill: "#8c8c8c" },
  "base-mask": { x: 460, y: 120, w: 104, h: 190, fill: "#2b2414" },
  head: { x: 450, y: 100, w: 124, h: 210, fill: "#a87f3b" },
  face: { x: 470, y: 220, w: 84, h: 80, fill: "#f4a13a" },
  "ring-1": { x: 690, y: 870, w: 18, h: 18, fill: "#d8f05a" },
  "ring-2": { x: 710, y: 870, w: 18, h: 18, fill: "#d8f05a" },
  "weapon-primary": { x: 660, y: 820, w: 120, h: 300, fill: "#c79eff" },
};

export default function PaperDollBG3({
  loadout,
  elementTint,
  width = 512,
  bodySpecies,
  showPlaceholders = false,
}: Props) {
  if (!hasRequiredBaseLayers(loadout)) {
    return (
      <div className="font-mono text-xs text-muted-foreground/60 p-4 rounded border border-red-500/40">
        PaperDollBG3: base-mask or base-suit missing. Run
        resolveStarterLoadout() before rendering.
      </div>
    );
  }

  const layers: readonly CompositedLayer[] = compositePaperDoll(loadout);
  const aspect = CANVAS_H / CANVAS_W;
  const height = Math.round(width * aspect);

  return (
    <div
      role="img"
      aria-label="Paper doll preview"
      style={{
        position: "relative",
        width,
        height,
        background: "transparent",
      }}
    >
      {/* Bottom-most layer: per-species silhouette so the gear sits on a
          body instead of floating in space. Sits below every gear layer
          (z=2) but above the aura (z=0) so the aura still glows from
          behind the figure. */}
      {bodySpecies ? <BodyLayer species={bodySpecies} /> : null}
      {layers.map((layer) => (
        <PieceLayer
          key={`${layer.slot}:${layer.layerZ}`}
          layer={layer}
          elementTint={elementTint}
          showPlaceholder={showPlaceholders}
        />
      ))}
    </div>
  );
}

interface BodyLayerProps {
  species: BodySpecies;
}

/** Per-species body silhouette. Renders the shipped PNG when present;
 *  on 404 it renders nothing — the gear layers above will still draw,
 *  just without a body underneath. We intentionally do not surface a
 *  coloured rectangle here: a labelled "body" placeholder on a
 *  player-facing card looks worse than no body at all. */
function BodyLayer({ species }: BodyLayerProps) {
  const [failed, setFailed] = useState(false);
  if (failed) return null;
  return (
    <div
      style={{
        position: "absolute",
        inset: 0,
        zIndex: 2,
        pointerEvents: "none",
      }}
    >
      <ResponsiveImage
        src={bodyArtUrl(species)}
        alt={`${species} body silhouette`}
        onError={() => setFailed(true)}
        style={{
          position: "absolute",
          inset: 0,
          width: "100%",
          height: "100%",
          objectFit: "contain",
        }}
      />
    </div>
  );
}

interface PieceLayerProps {
  layer: CompositedLayer;
  elementTint?: string;
  /** When true, fall through to a coloured placeholder rectangle if the
   *  art doesn't load — useful in the Suit Gallery for QA. When false
   *  (default for player-facing surfaces), render nothing so missing
   *  pieces simply don't appear instead of leaking slot labels. */
  showPlaceholder: boolean;
}

/**
 * One composited slot. Tries the suit PNG first; on 404 or
 * non-suit artIds either falls back to a slot-specific placeholder
 * rectangle (gallery / QA) or renders nothing (player surfaces).
 */
function PieceLayer({ layer, elementTint, showPlaceholder }: PieceLayerProps) {
  const parsed = parseSuitPieceArtId(layer.artId);
  const [imgFailed, setImgFailed] = useState(false);
  const shouldRenderImage = parsed !== null && !imgFailed;

  if (!shouldRenderImage) {
    if (!showPlaceholder) return null;
    return (
      <PlaceholderRect
        slot={layer.slot}
        layerZ={layer.layerZ}
        tint={layer.tintMask ? elementTint : undefined}
      />
    );
  }

  const src = suitArtUrl(parsed.setId, parsed.rarity, parsed.slot);

  return (
    <div
      style={{
        position: "absolute",
        inset: 0,
        zIndex: layer.layerZ,
        pointerEvents: "none",
      }}
    >
      <ResponsiveImage
        src={src}
        alt={`${parsed.setId} ${parsed.rarity} ${parsed.slot}`}
        onError={() => setImgFailed(true)}
        style={{
          position: "absolute",
          inset: 0,
          width: "100%",
          height: "100%",
          objectFit: "contain",
        }}
      />
      {layer.tintMask && elementTint ? (
        <div
          aria-hidden
          style={{
            position: "absolute",
            inset: 0,
            background: elementTint,
            mixBlendMode: "multiply",
            opacity: 0.35,
            pointerEvents: "none",
          }}
        />
      ) : null}
    </div>
  );
}

interface PlaceholderRectProps {
  slot: SuitEquipSlot;
  layerZ: number;
  tint?: string;
}

function PlaceholderRect({ slot, layerZ, tint }: PlaceholderRectProps) {
  const rect = SLOT_RECTS[slot];
  if (!rect) return null;
  const fill = tint ?? rect.fill;
  // Position in the 1024×1536 grid as percentages so the
  // placeholder scales with the canvas container.
  // Coloured rectangle only — slot labels are kept on the data attribute
  // for QA tooling, not rendered as text. A "weapon-primary" caption on
  // the chronicle card is worse than the missing PNG it stands in for.
  return (
    <div
      data-slot={slot}
      style={{
        position: "absolute",
        left: `${(rect.x / CANVAS_W) * 100}%`,
        top: `${(rect.y / CANVAS_H) * 100}%`,
        width: `${(rect.w / CANVAS_W) * 100}%`,
        height: `${(rect.h / CANVAS_H) * 100}%`,
        background: fill,
        border: "1px solid rgba(0,0,0,0.4)",
        opacity: 0.9,
        zIndex: layerZ,
        pointerEvents: "none",
      }}
    />
  );
}

/**
 * Returns true iff the DRESSUP_V2 feature flag is currently enabled
 * for this browser. Callers can gate component imports off this —
 * the flag flips default once the real PNG catalog ships and the
 * renderer switches off placeholder rectangles.
 */
export function isDressupV2Enabled(): boolean {
  if (typeof window === "undefined") return false;
  // Build-time override wins.
  const buildFlag = (import.meta as unknown as { env?: Record<string, string> })
    .env?.VITE_DRESSUP_V2;
  if (buildFlag === "on") return true;
  try {
    return window.localStorage.getItem("DRESSUP_V2") === "on";
  } catch {
    return false;
  }
}
